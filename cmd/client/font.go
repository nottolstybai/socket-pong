// fontTextWidth returns the width in pixels of text at the given scale.
func fontTextWidth(text string, scale int) int {
	n := len([]rune(text))
	if n == 0 {
		return 0
	}
	return (n*fontAdvance - 1) * scale
}

// drawText additively draws pixel text with its top-left corner at x, y.
func (c *canvas) drawText(x, y float64, text string, scale int, color rgb) {
	s := float64(scale)
	// Whole pixels only: a blocky font blurs badly at fractional positions.
	x, y = math.Round(x), math.Round(y)
	for _, r := range text {
		if rows, ok := font[r]; ok {
			for gy, line := range rows {
				for gx, bit := range line {
					if bit != '#' {
						continue
					}
					px := x + float64(gx)*s
					py := y + float64(gy)*s
					c.rect(px, py, px+s, py+s, color)
				}
			}
		}
		x += fontAdvance * s
	}
}

// drawTextCentered centres pixel text horizontally around cx.
func (c *canvas) drawTextCentered(cx, y float64, text string, scale int, color rgb) {
	c.drawText(cx-float64(fontTextWidth(text, scale))/2, y, text, scale, color)
}
